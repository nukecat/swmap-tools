"""Unpack a map into a folder of editable files and pack it back.

  map.json              header + environment + terrain settings
  preview.jpg           container preview (regenerated by `pack --regenerate-preview`)
  objects.json          all props (JSON array)
  terrain/heightmap.png 16-bit grayscale, metres = value*500/65536 - 100
  terrain/paint_NN.png  8-bit grayscale weights of layer NN (layer 00 = implied base, not stored)
  _derived/             read-only helper images, ignored by pack
"""
from __future__ import annotations
import json, shutil, uuid
from pathlib import Path

import numpy as np
from PIL import Image

from .binio import FormatError
from .model import (SwMap, Header, Environment, Terrain, Prop, now_ticks, ticks_to_iso, iso_to_ticks, Kind, Team)
from .preview import render_preview
from . import terrain as T

FORMAT = "swmap-folder/2"
VEHICLES = {1: "tank", 2: "boat", 4: "plane"}
VEHICLE_BY_NAME = {v: k for k, v in VEHICLES.items()}


def _f32(x: float) -> float:
    """Shortest decimal that still round-trips to the same float32 (nicer JSON: 0.85, not 0.8500000238)."""
    return float(np.format_float_positional(np.float32(x), unique=True, trim="-"))


def _hex(c) -> str:
    return "#%02x%02x%02x" % tuple(c)


def _unhex(s: str):
    s = s.lstrip("#")
    if len(s) != 6:
        raise ValueError(f"bad colour {s!r}")
    return tuple(int(s[i:i + 2], 16) for i in (0, 2, 4))


# ---------------------------------------------------------------- props <-> json
def _xyz(v) -> dict:
    return {"x": v[0], "y": v[1], "z": v[2]}


def _unxyz(d, what) -> tuple:
    try:
        return (float(d["x"]), float(d["y"]), float(d["z"]))
    except (TypeError, KeyError):
        raise ValueError(f"{what} must be an object like {{\"x\": 0, \"y\": 0, \"z\": 0}}, got {d!r}") from None


def prop_to_json(p: Prop) -> dict:
    d = {"kind": p.kind}
    if p.kind == KIND_MODEL:
        d["model_id"] = p.model_id
    d["position"] = _xyz(p.position)                       # metres, y is up (exact: multiples of 1/128)
    if p.kind == KIND_CAPTURE_POINT:
        pass                                               # capture points cannot be rotated (always 0)
    elif p.yaw_deg is not None:
        d["yaw_deg"] = round(p.yaw_deg, 4)                 # stored in steps of 360/65536 deg
    else:
        # quaternion, stored as signed 16-bit / 32767. The game normalises it on load.
        d["quaternion"] = {k: round(v / 32767.0, 6) for k, v in zip("xyzw", p.quat_rotation)}
    if p.scale is not None:
        if isinstance(p.scale, (int, float)):
            d["radius" if p.kind == KIND_CAPTURE_POINT else "uniform_scale"] = _f32(p.scale)
        else:
            d["scale"] = {k: _f32(v) for k, v in zip("xyz", p.scale)}
    if p.kind == KIND_MODEL:
        if p.color is not None: d["color"] = _hex(p.color)
        if p.floors is not None: d["floors"] = p.floors
        if p.collision != "default": d["collision"] = p.collision
    elif p.kind == KIND_SPAWN:
        d["team"] = TEAMS[p.team] if p.team < 3 else p.team
        d["vehicle"] = VEHICLES.get(p.spawn_type, p.spawn_type)
        if p.reserve: d["reserve"] = True
    elif p.kind == KIND_CAPTURE_POINT:
        d["letter"] = "abcd"[p.letter] if p.letter < 4 else p.letter
    return d


def prop_from_json(d: dict) -> Prop:
    kind = KIND_BY_NAME[d["kind"]]
    p = Prop(kind=kind, position=_unxyz(d["position"], "position"))
    if kind == KIND_MODEL:
        p.model_id = int(d["model_id"])
    if "quaternion" in d:
        if "yaw_deg" in d:
            raise ValueError("use either yaw_deg or quaternion, not both")
        q = d["quaternion"]
        p.quat_rotation = tuple(int(round(float(q[k]) * 32767.0)) for k in "xyzw")
    else:
        p.yaw_deg = float(d.get("yaw_deg", 0.0))
    if "radius" in d or "uniform_scale" in d:
        if "scale" in d:
            raise ValueError("use either uniform_scale/radius or scale, not both")
        p.scale = float(d.get("radius", d.get("uniform_scale")))
    elif "scale" in d:
        p.scale = _unxyz(d["scale"], "scale")
    if kind == KIND_MODEL:
        if "color" in d: p.color = _unhex(d["color"])
        if "floors" in d: p.floors = int(d["floors"])
        p.collision = d.get("collision", "default")
    elif kind == KIND_SPAWN:
        t = d.get("team", "deathmatch")
        p.team = TEAMS.index(t) if isinstance(t, str) else int(t)
        v = d.get("vehicle", "tank")
        p.spawn_type = VEHICLE_BY_NAME[v] if isinstance(v, str) else int(v)
        p.reserve = bool(d.get("reserve", False))
    elif kind == KIND_CAPTURE_POINT:
        l = d.get("letter", "a")
        p.letter = "abcd".index(l) if isinstance(l, str) else int(l)
    return p


# ---------------------------------------------------------------- png helpers
def _save_png16(a, path):
    Image.fromarray(np.asarray(a, dtype=np.uint16)).save(path)


def _save_png8(a, path):
    Image.fromarray(np.asarray(a, dtype=np.uint8), "L").save(path)


def _load_gray(path, dtype):
    im = Image.open(path)
    if dtype == np.uint16:
        if im.mode not in ("I;16", "I;16L", "I"):
            raise FormatError(f"{path.name}: expected a 16-bit grayscale PNG, got mode {im.mode}. "
                              "Save the heightmap as 16-bit grayscale.")
        return np.array(im).astype(np.uint16)
    if im.mode not in ("L", "P"):
        im = im.convert("L")
    return np.array(im).astype(np.uint8)


# ---------------------------------------------------------------- folder IO
def write_folder(m: SwMap, folder, force=False, derived=True):
    folder = Path(folder)
    if folder.exists() and any(folder.iterdir()):
        if not force:
            raise FileExistsError(f"{folder} is not empty (use --force)")
    (folder / "terrain").mkdir(parents=True, exist_ok=True)
    h, e, t = m.header, m.environment, m.terrain
    meta = {
        "format": FORMAT,
        "name": h.name, "author": h.author, "guid": str(h.guid),
        "size_m": _f32(h.size_m),
        "modified": ticks_to_iso(h.modified_ticks),
        "environment": {
            "water": e.water, "ice": e.ice, "edge_walls": e.edge_walls, "fog": e.fog,
            "time": _f32(e.time), "weather": e.weather,
            "shadow_distance_m": e.shadow_distance_units / 2,
            "fog_mode": e.fog_mode, "fog_color": _hex(e.fog_color),
            "fog_distance_m": e.fog_distance_units / 2,
        },
        "paint_layer_ids": t.layer_ids,
    }
    if h.version != 1:
        meta["container_version"] = h.version
    if not t.layers:                                   # only then the resolution is not implied by a PNG
        meta["paint_resolution"] = t.paint_resolution
    (folder / "map.json").write_text(json.dumps(meta, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    if m.preview_jpg:
        (folder / "preview.jpg").write_bytes(m.preview_jpg)
    (folder / "objects.json").write_text(
        json.dumps([prop_to_json(p) for p in m.props], indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    _save_png16(t.heights, folder / "terrain" / "heightmap.png")
    for i, layer in enumerate(t.layers, 1):
        _save_png8(layer, folder / "terrain" / f"paint_{i:02d}.png")
    (folder / "README.txt").write_text(README, encoding="utf-8")
    if derived:
        d = folder / "_derived"
        d.mkdir(exist_ok=True)
        if t.layers:
            _save_png8(T.base_layer(t.layers), d / "paint_00_base.png")
        z = T.height_to_m(t.heights)
        span = max(float(z.max() - z.min()), 1e-9)
        Image.fromarray(((z - z.min()) / span * 255).astype(np.uint8), "L").save(d / "heightmap_preview.png")
        (d / "NOTE.txt").write_text("Generated for convenience. `swmap pack` ignores this folder.\n")


def read_folder(folder, regenerate_preview=False, touch=False) -> SwMap:
    folder = Path(folder)
    try:
        meta = json.loads((folder / "map.json").read_text(encoding="utf-8"))
    except FileNotFoundError:
        raise FormatError(f"{folder}: map.json not found - is this an unpacked map folder?") from None
    if meta.get("format") != FORMAT:
        raise FormatError(f"unsupported folder format {meta.get('format')!r}")
    ev = meta["environment"]
    header = Header(uuid.UUID(meta["guid"]), meta["name"], meta.get("author", ""), iso_to_ticks(meta["modified"]),
                    float(meta["size_m"]), int(meta.get("container_version", 1)))
    if touch:
        header.modified_ticks = now_ticks()
    env = Environment(
        water=bool(ev["water"]), ice=bool(ev["ice"]), edge_walls=bool(ev["edge_walls"]), fog=bool(ev["fog"]),
        time=float(ev["time"]), weather=int(ev["weather"]),
        shadow_distance_units=int(round(float(ev["shadow_distance_m"]) * 2)),
        fog_mode=int(ev["fog_mode"]), fog_color=_unhex(ev["fog_color"]),
        fog_distance_units=int(round(float(ev["fog_distance_m"]) * 2)))
    heights = _load_gray(folder / "terrain" / "heightmap.png", np.uint16)
    ids = [int(i) for i in meta["paint_layer_ids"]]
    layers = []
    for i in range(1, len(ids)):
        p = folder / "terrain" / f"paint_{i:02d}.png"
        if not p.exists():
            raise FormatError(f"missing {p.relative_to(folder)} (layer ids: {ids})")
        layers.append(_load_gray(p, np.uint8))
    terr = Terrain(heights, ids, layers, layers[0].shape[0] if layers else int(meta["paint_resolution"]))
    objs = json.loads((folder / "objects.json").read_text(encoding="utf-8"))
    if not isinstance(objs, list):
        raise FormatError("objects.json must be a JSON array of objects")
    props = [prop_from_json(d) for d in objs]
    jpg = b""
    pj = folder / "preview.jpg"
    if pj.exists() and not regenerate_preview:
        jpg = pj.read_bytes()
    else:
        jpg = render_preview(terr, header.size_m)
    return SwMap(header, env, terr, props, jpg)


README = """Unpacked .swmap
===============
map.json            name, author, GUID, size, modified time, environment (distances in metres), paint layer ids
objects.json        array of props. position {x, y (up), z} in metres; yaw_deg or quaternion; kinds:
                    model | spawn (team, vehicle: tank/boat/plane) | capture_point (radius, letter) | player_spawn
terrain/heightmap.png   16-bit grayscale. metres = value * 500 / 65536 - 100   (-100 .. 400 m)
terrain/paint_NN.png    8-bit grayscale weight of paint layer NN. Layer 00 (the base) is implied:
                        255 - sum(other layers). Keep every pixel's sum <= 255.
preview.jpg         shown in the map list; `swmap pack --regenerate-preview` makes a top-down placeholder
_derived/           helper images, ignored when packing

Edit, then:  swmap pack <this folder> -o map.swmap
"""
