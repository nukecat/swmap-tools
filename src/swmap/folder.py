"""Unpack a map into a folder of editable files and pack it back.

  map.json              header + environment + terrain settings
  preview.jpg           container preview (regenerated by `pack --regenerate-preview`)
  objects.json          all objects (JSON array), positions in metres
  terrain/heightmap.png 16-bit grayscale, metres = -100 + value / 65535 * 500
  terrain/paint_NN.png  8-bit weights of paint layer NN (NN = index in paint_layer_ids; the LAST layer is implied)
  _derived/             read-only helper images, ignored by pack

The binary format is swformats' (https://github.com/xmake-studio/sw-formats); this module only maps its
MapObject / Terrain / Environment to files a person can edit. Distances in the JSON are metres, swformats uses
world units (2 per metre).
"""
from __future__ import annotations
import datetime
import json
import re
import uuid
from pathlib import Path

import numpy as np
from PIL import Image
from swformats import FormatError, swmap as sw
from swformats.swmap import MapObject, SwMap

from .fileio import DEFAULT_LEVEL, MapFile
from .preview import render_preview
from . import terrain as T

FORMAT = "swmap-folder/5"
_OLD_FORMAT = "swmap-folder/4"     # same files, but paint_NN.png was numbered from 1 and deflate_level defaulted to 6
M = sw.METERS_TO_UNITS

KINDS = {sw.PROP: "prop", sw.SPAWN: "spawn", sw.CAPTURE_POINT: "capture_point", sw.PLAYER_SPAWN: "player_spawn"}
TEAMS = {sw.TEAM_DEATHMATCH: "ffa", sw.TEAM_RED: "red", sw.TEAM_BLUE: "blue"}
VEHICLES = {sw.SPAWN_GROUND: "tank", sw.SPAWN_WATER: "boat", sw.SPAWN_AIRCRAFT: "plane"}
LETTERS = {0: "a", 1: "b", 2: "c", 3: "d"}
WEATHER = {0: "clear", 1: "sunny", 2: "cloudy", 3: "rain"}
FOG_MODES = {sw.FOG_LINEAR: "linear", sw.FOG_EXPONENTIAL: "exponential", sw.FOG_EXPONENTIAL_SQUARED: "exp_squared"}
_ALIASES = {"model": sw.PROP, "deathmatch": sw.TEAM_DEATHMATCH, "ground": sw.SPAWN_GROUND, "water": sw.SPAWN_WATER,
            "aircraft": sw.SPAWN_AIRCRAFT}


# ---------------------------------------------------------------- small helpers
def _f32(x: float) -> float:
    """Shortest decimal that still round-trips to the same float32 (nicer JSON: 0.85, not 0.8500000238)."""
    return float(np.format_float_positional(np.float32(x), unique=True, trim="-"))


def _hex(c) -> str:
    return "#%02x%02x%02x" % tuple(c[:3])


def _unhex(s: str, alpha: bool = False):
    """'#rrggbb' -> (r, g, b). With alpha=True also '#rrggbbaa'; '#rrggbb' then means opaque."""
    s = str(s).lstrip("#")
    if len(s) not in ((6, 8) if alpha else (6,)):
        raise ValueError(f"bad colour {s!r} (expected {'#rrggbb or #rrggbbaa' if alpha else '#rrggbb'})")
    try:
        v = tuple(int(s[i:i + 2], 16) for i in range(0, len(s), 2))
    except ValueError:
        raise ValueError(f"bad colour {s!r}") from None
    return v + (0xFF,) if alpha and len(v) == 3 else v


def _name(table, v):
    """value -> lowercase name; a value the game does not define stays a number (validate warns)."""
    return table.get(v, int(v))


def _value(table, x, what):
    """'red' / 'RED' / 1 -> the value; numbers the game does not define are kept (validate warns)."""
    if isinstance(x, str):
        key = x.strip().lower()
        if key in _ALIASES and _ALIASES[key] in table:
            return _ALIASES[key]
        for v, n in table.items():
            if n == key:
                return v
        raise ValueError(f"unknown {what} {x!r} (expected one of: {', '.join(table.values())})")
    return int(x)


# ---------------------------------------------------------------- time stamps
_TICKS_PER_DAY = 864_000_000_000


def ticks_to_iso(ticks: int) -> str:
    """.NET ticks -> 'YYYY-MM-DDTHH:MM:SS.fffffffZ' (100 ns resolution, lossless)."""
    days, rem = divmod(ticks, _TICKS_PER_DAY)
    secs, frac = divmod(rem, 10_000_000)
    d = datetime.date.fromordinal(days + 1)
    return f"{d.year:04d}-{d.month:02d}-{d.day:02d}T{secs // 3600:02d}:{secs // 60 % 60:02d}:{secs % 60:02d}.{frac:07d}Z"


def iso_to_ticks(s: str) -> int:
    mt = re.fullmatch(r"(\d{4})-(\d\d)-(\d\d)[T ](\d\d):(\d\d):(\d\d)(?:\.(\d{1,7}))?(?:Z|\+00:00)?", s.strip())
    if not mt:
        raise ValueError(f"bad timestamp {s!r}; expected e.g. 2026-10-03T06:34:05.6442096Z (UTC)")
    y, mo, d, h, mi, se = (int(g) for g in mt.groups()[:6])
    frac = int((mt.group(7) or "0").ljust(7, "0"))
    days = datetime.date(y, mo, d).toordinal() - 1
    return days * _TICKS_PER_DAY + (h * 3600 + mi * 60 + se) * 10_000_000 + frac


# ---------------------------------------------------------------- objects <-> json
def _xyz(v, k=1.0) -> dict:
    return {"x": v[0] * k, "y": v[1] * k, "z": v[2] * k}


def _unxyz(d, what, k=1.0):
    try:
        return (float(d["x"]) * k, float(d["y"]) * k, float(d["z"]) * k)
    except (TypeError, KeyError):
        raise ValueError(f"{what} must be an object like {{\"x\": 0, \"y\": 0, \"z\": 0}}, got {d!r}") from None


def is_tilted(o: MapObject) -> bool:
    """Only props can be tilted; swformats writes the others (and flat props) as a plain yaw, like the game."""
    return o.kind == sw.PROP and not (abs(o.rotation[0]) < 1e-4 and abs(o.rotation[2]) < 1e-4)


def obj_to_json(o: MapObject) -> dict:
    d = {"kind": _name(KINDS, o.kind)}
    if o.kind == sw.PROP:
        d["prop_id"] = o.prop_id
    d["position"] = _xyz(o.position, 1 / M)                # metres, y is up (exact: multiples of 1/128)
    if o.kind == sw.CAPTURE_POINT:
        pass                                               # cannot be rotated (always 0)
    elif is_tilted(o):
        d["rotation"] = {k: float(v) for k, v in zip("xyzw", o.rotation)}   # stored as signed 16-bit / 32767
    else:
        d["rotation"] = round(o.yaw % 360.0, 4)            # yaw in degrees, stored in steps of 360/65536
    s = o.scale
    if o.kind == sw.CAPTURE_POINT:
        d["radius"] = _f32(s[0])
    elif s[0] == s[1] == s[2]:
        if s[0] != 1.0:
            d["size"] = _f32(s[0])
    else:
        d["scale"] = {k: _f32(v) for k, v in zip("xyz", s)}
    if o.kind == sw.PROP:
        if o.color is not None:
            d["color"] = _hex(o.color) if o.color[3] == 0xFF else "#%02x%02x%02x%02x" % tuple(o.color)
        if o.floors:
            d["floors"] = o.floors
        if o.collision != sw.COLLISION_DEFAULT:
            d["collision"] = o.collision == sw.COLLISION_ON    # true / false; absent = the prop's default
        if o.glow:
            d["glow"] = True
    elif o.kind == sw.SPAWN:
        d["team"] = _name(TEAMS, o.team)
        d["vehicle_type"] = _name(VEHICLES, o.spawn_type)
        if o.reserve:
            d["reserve"] = True
    elif o.kind == sw.CAPTURE_POINT:
        d["letter"] = _name(LETTERS, o.letter)
    return d


def obj_from_json(d: dict) -> MapObject:
    kind = _value(KINDS, d["kind"], "kind")
    o = MapObject(kind=kind, position=_unxyz(d["position"], "position", M))
    if kind == sw.PROP:
        pid = d.get("prop_id", d.get("model_id"))           # model_id: older folders
        if pid is None:
            raise ValueError(f"prop without a prop_id: {d!r}")
        o.prop_id = int(pid)
    r = d.get("rotation", 0.0)
    if isinstance(r, dict):
        try:
            o.rotation = tuple(float(r[k]) for k in "xyzw")
        except (TypeError, KeyError):
            raise ValueError(f"rotation must be a number (degrees) or an object like "
                             f"{{\"x\": 0, \"y\": 0, \"z\": 0, \"w\": 1}}, got {r!r}") from None
    else:
        o.yaw = float(r)
    if "radius" in d or "size" in d:
        if "scale" in d:
            raise ValueError("use either size/radius or scale, not both")
        s = float(d["radius"] if "radius" in d else d["size"])
        o.scale = (s, s, s)
    elif "scale" in d:
        o.scale = _unxyz(d["scale"], "scale")
    if kind == sw.PROP:
        if "color" in d:
            o.color = _unhex(d["color"], alpha=True)
        o.floors = int(d.get("floors", 0))
        c = d.get("collision")
        if c is not None and not isinstance(c, bool):
            raise ValueError(f"collision must be true or false (or left out for the default), got {c!r}")
        o.collision = sw.COLLISION_DEFAULT if c is None else sw.COLLISION_ON if c else sw.COLLISION_OFF
        o.glow = bool(d.get("glow", False))
    elif kind == sw.SPAWN:
        o.team = _value(TEAMS, d.get("team", "ffa"), "team")
        o.spawn_type = _value(VEHICLES, d.get("vehicle_type", "tank"), "vehicle_type")
        o.reserve = bool(d.get("reserve", False))
    elif kind == sw.CAPTURE_POINT:
        o.letter = _value(LETTERS, d.get("letter", "a"), "letter")
    return o


# ---------------------------------------------------------------- png helpers
# Terrain arrays are indexed [z, x] with row 0 at z = -size/2. Images have row 0 at the top, so the arrays are flipped
# along the y axis of the image: the top of every PNG is +z, the left edge is -x (a top-down view of the map).
def _save_png16(a, path):
    Image.fromarray(np.ascontiguousarray(np.asarray(a, dtype=np.uint16)[::-1])).save(path)


def _save_png8(a, path):
    Image.fromarray(np.ascontiguousarray(np.asarray(a, dtype=np.uint8)[::-1]), "L").save(path)


def _load_gray(path: Path, dtype):
    im = Image.open(path)
    if dtype == np.uint16:
        if im.mode not in ("I;16", "I;16L", "I"):
            raise FormatError(f"{path.name}: expected a 16-bit grayscale PNG, got mode {im.mode}. "
                              "Save the heightmap as 16-bit grayscale.")
        return np.ascontiguousarray(np.array(im).astype(np.uint16)[::-1])
    if im.mode not in ("L", "P"):
        im = im.convert("L")
    return np.ascontiguousarray(np.array(im).astype(np.uint8)[::-1])


# ---------------------------------------------------------------- folder IO
def write_folder(mf, folder, force=False, derived=True, mark_no_preview=True):
    """mf: a MapFile (or a bare swformats SwMap). A map without a preview is marked `"preview": false` so that pack
    does not invent one (byte-identical round trips); pass mark_no_preview=False to have pack generate it."""
    if isinstance(mf, SwMap):
        mf = MapFile(mf)
    m = mf.map
    folder = Path(folder)
    if folder.exists() and any(folder.iterdir()) and not force:
        raise FileExistsError(f"{folder} is not empty (use --force)")
    (folder / "terrain").mkdir(parents=True, exist_ok=True)
    e, t = m.env, m.terrain
    meta = {
        "format": FORMAT,
        "name": m.name, "author": m.author, "guid": str(uuid.UUID(m.id)),
        "size_m": _f32(t.size_meters),
        "modified": ticks_to_iso(m.modified_ticks),
        "environment": {
            "water": e.water, "ice": e.ice, "edge_walls": e.edge_walls, "fog": e.fog,
            "time": _f32(e.time), "weather": _name(WEATHER, e.weather),
            "shadow_distance_m": e.shadow_distance / M,
            "fog_mode": _name(FOG_MODES, e.fog_mode), "fog_color": _hex(e.fog_color),
            "fog_distance_m": e.fog_distance / M,
        },
        "paint_layer_ids": list(t.layer_ids),
    }
    if mf.level != DEFAULT_LEVEL:                      # the game has also written level 6; keeps pack byte-identical
        meta["deflate_level"] = mf.level
    if not m.preview_jpeg and mark_no_preview:
        meta["preview"] = False                        # the map has no preview; do not invent one
    if t.layer_count == 1:                             # only then the resolution is not implied by a PNG
        meta["paint_resolution"] = t.alpha_res
    (folder / "map.json").write_text(json.dumps(meta, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    if m.preview_jpeg:
        (folder / "preview.jpg").write_bytes(m.preview_jpeg)
    (folder / "objects.json").write_text(
        json.dumps([obj_to_json(o) for o in m.objects], indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    heights, splat = T.heights_array(t), T.splat_array(t)
    _save_png16(heights, folder / "terrain" / "heightmap.png")
    for i in range(t.layer_count - 1):                 # the last layer is implied: 255 - sum(the others)
        _save_png8(splat[:, :, i], folder / "terrain" / f"paint_{i:02d}.png")
    (folder / "README.txt").write_text(README, encoding="utf-8")
    if derived:
        d = folder / "_derived"
        d.mkdir(exist_ok=True)
        last = t.layer_count - 1
        _save_png8(splat[:, :, last], d / f"paint_{last:02d}_implied.png")
        z = T.height_to_m(heights)[::-1]
        span = max(float(z.max() - z.min()), 1e-9)
        Image.fromarray(((z - z.min()) / span * 255).astype(np.uint8), "L").save(d / "heightmap_preview.png")
        (d / "NOTE.txt").write_text("Generated for convenience. `swmap pack` ignores this folder.\n")


def read_folder(folder, regenerate_preview=False, touch=False) -> MapFile:
    folder = Path(folder)
    try:
        meta = json.loads((folder / "map.json").read_text(encoding="utf-8"))
    except FileNotFoundError:
        raise FormatError(f"{folder}: map.json not found - is this an unpacked map folder?") from None
    fmt = meta.get("format")
    if fmt not in (FORMAT, _OLD_FORMAT):
        raise FormatError(f"unsupported folder format {fmt!r}")
    old = fmt == _OLD_FORMAT
    notes = []
    ev = meta["environment"]
    env = sw.Environment(
        water=bool(ev["water"]), ice=bool(ev["ice"]), edge_walls=bool(ev["edge_walls"]), fog=bool(ev["fog"]),
        time=float(ev["time"]), weather=_value(WEATHER, ev["weather"], "weather"),
        shadow_distance=int(round(float(ev["shadow_distance_m"]) * M)),
        fog_mode=_value(FOG_MODES, ev["fog_mode"], "fog_mode"), fog_color=_unhex(ev["fog_color"]),
        fog_distance=int(round(float(ev["fog_distance_m"]) * M)))

    heights = _load_gray(folder / "terrain" / "heightmap.png", np.uint16)
    if heights.shape[0] != heights.shape[1]:
        raise FormatError(f"heightmap.png must be square, is {heights.shape[1]}x{heights.shape[0]}")
    ids = [int(i) for i in meta["paint_layer_ids"]]
    n = len(ids)
    planes = []
    for i in range(n - 1):
        name = f"paint_{i + 1 if old else i:02d}.png"      # folder/4 numbered the stored layers from 1
        p = folder / "terrain" / name
        if not p.exists():
            raise FormatError(f"missing terrain/{name} (layer ids: {ids})")
        planes.append(_load_gray(p, np.uint8))
    res = planes[0].shape[0] if planes else int(meta["paint_resolution"])
    for i, pl in enumerate(planes):
        if pl.shape != (res, res):
            raise FormatError(f"paint layer {i} is {pl.shape[1]}x{pl.shape[0]}, expected {res}x{res}")
    weights = np.zeros((res, res, n), np.uint8)
    total = np.zeros((res, res), np.int32)
    for i, pl in enumerate(planes):
        weights[:, :, i] = pl
        total += pl
    if total.max(initial=0) > 255:
        notes.append(f"paint weights add up to more than 255 in {int((total > 255).sum())} texels; the game caps "
                     "the later layers there (keep the sum of all stored layers <= 255)")
    if n:
        weights[:, :, n - 1] = np.clip(255 - total, 0, 255)       # the implied last layer

    t = sw.Terrain(size_meters=float(meta["size_m"]), height_res=int(heights.shape[0]), heights=heights.ravel().tolist(),
                   alpha_res=res, layer_ids=ids, splat=bytearray(weights.tobytes()))
    objs = json.loads((folder / "objects.json").read_text(encoding="utf-8"))
    if not isinstance(objs, list):
        raise FormatError("objects.json must be a JSON array of objects")

    m = SwMap(id=uuid.UUID(meta["guid"]).hex, name=meta["name"], author=meta.get("author", ""),
              modified_ticks=iso_to_ticks(meta["modified"]), env=env, terrain=t,
              objects=[obj_from_json(d) for d in objs])
    if touch:
        m.touch()
    pj = folder / "preview.jpg"
    if pj.exists() and not regenerate_preview:
        m.preview_jpeg = pj.read_bytes()
    elif meta.get("preview") is False and not regenerate_preview:
        m.preview_jpeg = None                                       # unpacked from a map that had none
    else:
        m.preview_jpeg = render_preview(t)
    return MapFile(m, int(meta.get("deflate_level", 6 if old else DEFAULT_LEVEL)), notes)


README = """Unpacked .swmap
===============
map.json            name, author, GUID, size, modified time, environment (distances in metres), paint layer ids
objects.json        array of objects. position {x, y (up), z} in metres; rotation (degrees, or {x,y,z,w}); kinds:
                    prop (prop_id) | spawn (team, vehicle_type: tank/boat/plane) | capture_point (radius, letter) | player_spawn
terrain/heightmap.png   16-bit grayscale. metres = -100 + value / 65535 * 500   (-100 .. 400 m)
terrain/paint_NN.png    8-bit grayscale weight of paint layer NN (NN = position in paint_layer_ids, from 00).
                        The LAST layer is implied: 255 - sum(the others). Keep every pixel's sum <= 255.
preview.jpg         shown in the map list; `swmap pack --regenerate-preview` makes a top-down placeholder
_derived/           helper images, ignored when packing

Edit, then:  swmap pack <this folder> -o map.swmap
Format details: https://github.com/xmake-studio/sw-formats/blob/main/docs/swmap.md
"""
